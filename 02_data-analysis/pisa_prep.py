ROOT = Path(__file__).resolve().parents[1]
CLEAN_DIR = ROOT / "data/clean"
CLEAN_TABLE_PATH = CLEAN_DIR / "pisa6_clean.parquet"
COLUMN_ROLES_PATH = CLEAN_DIR / "columns.json"
FOLDS_PATH = CLEAN_DIR / "folds.csv"

COLUMN_ROLES = json.loads(COLUMN_ROLES_PATH.read_text())
SYSTEMS = ["ARE", "SAU", "QAT", "JOR", "MAR", "PSE"]
SYSTEM_COL, SCHOOL_COL = "CNT", "CNTSCHID"
PV_COLS = COLUMN_ROLES["targets"]["regression"]                 # PV1MATH ... PV10MATH
BELOW_L2_COLS = COLUMN_ROLES["targets"]["classification"]       # BELOW_L2_PV1 ... BELOW_L2_PV10
FEATURES_BY_GROUP = COLUMN_ROLES["feature_groups"]              # group name -> list of feature columns
MISSING_FLAGS_BY_GROUP = COLUMN_ROLES["missing_indicators"]     # group name -> list of "<feature>_missing" columns
GROUPS = list(FEATURES_BY_GROUP)                                # the 5 factor groups
FEATURE_COLS = [feature for group_cols in FEATURES_BY_GROUP.values() for feature in group_cols]   # all 17
BINARY_FEATURE_COLS = ["SCHL_PRIVATE"]                          # 0/1 features: filled in, but not clipped or scaled

# Columns that must never be model inputs: every plausible value (maths, reading, science, subscales),
# the below-Level-2 targets, the weights, the school and student IDs, and Part A's audit-only columns.
LEAKY_COL_PATTERN = re.compile(r"^(PV\d+[A-Z]+|BELOW_L2_.*|W_FST.*|SENWT|CNTSCHID|CNTSTUID|.*_raw)$")

# ---------------------------------------------------------------------------------------------------------
# Fold settings. Fixed: change them only if the group agrees, then rebuild the fold file (notebook 03).
# ---------------------------------------------------------------------------------------------------------
N_FOLDS = 5
FOLD_SEED = 2022

# ---------------------------------------------------------------------------------------------------------
# Team decisions that are still open. These are the defaults until the group agrees.
# Changing one here changes it for everyone who uses this file.
# ---------------------------------------------------------------------------------------------------------
POOLED_WEIGHT_COL = "SENWT"       # 1. weight when the six systems are modelled together.
                                  #    "SENWT": each system counts equally. "W_FSTUWT": each system counts by its population.
USE_SYSTEM_AS_FEATURE = False     # 2. add the system (CNT) as a predictor, one-hot encoded
FAMILY_AS_ESCS_ONLY = False       # 3. family group = ESCS alone, instead of ESCS + its 3 parts (PAREDINT, HISEI, HOMEPOS)
CLIP_PERCENTILES = (1.0, 99.0)    # 4. cap numeric features at these training percentiles. None = don't clip.


def load_clean_table(cols: list[str] | None = None) -> pd.DataFrame:
    """Read the Part A clean table: all 151 columns, or only the ones in cols."""
    return pd.read_parquet(CLEAN_TABLE_PATH, columns=cols)


# ---------------------------------------------------------------------------------------------------------
# T07: the school-grouped folds
# ---------------------------------------------------------------------------------------------------------
def make_folds(table_df: pd.DataFrame, n_folds: int = N_FOLDS, seed: int = FOLD_SEED) -> pd.DataFrame:
    """Put every school in one of n_folds folds. Returns one row per school: CNTSCHID, CNT, fold, n_students.

    StratifiedGroupKFold keeps each school whole (the "group" part), and tries to give every fold the same
    mix of system x mostly-below-Level-2 students (the "stratified" part).
    """
    share_below_l2 = table_df[BELOW_L2_COLS].mean(axis=1)        # per student: fraction of the 10 PVs below Level 2
    stratum_by_student = table_df[SYSTEM_COL].astype(str) + "_" + np.where(share_below_l2 >= 0.5, "below", "above")
    splitter = StratifiedGroupKFold(n_splits=n_folds, shuffle=True, random_state=seed)
    fold_by_student = np.full(len(table_df), -1)
    for fold, (_, test_positions) in enumerate(splitter.split(table_df, stratum_by_student, groups=table_df[SCHOOL_COL])):
        fold_by_student[test_positions] = fold

    students_df = table_df[[SCHOOL_COL, SYSTEM_COL]].assign(fold=fold_by_student)
    if (students_df.groupby(SCHOOL_COL)["fold"].nunique() != 1).any():
        raise RuntimeError("a school was split across folds")
    folds_df = (students_df.groupby(SCHOOL_COL)
                .agg(CNT=(SYSTEM_COL, "first"), fold=("fold", "first"), n_students=("fold", "size"))
                .reset_index())
    return folds_df.sort_values(SCHOOL_COL).reset_index(drop=True)


def save_folds(folds_df: pd.DataFrame) -> None:
    """Write the fold file. Everyone then loads this file instead of making their own folds."""
    folds_df.to_csv(FOLDS_PATH, index=False)


def load_folds() -> pd.DataFrame:
    """Read the fold file: one row per school (CNTSCHID, CNT, fold, n_students)."""
    return pd.read_csv(FOLDS_PATH)


def get_fold_by_student(table_df: pd.DataFrame, folds_df: pd.DataFrame | None = None) -> pd.Series:
    """The test fold (0 to N_FOLDS-1) of each student, in the same row order as table_df.

    Use it as a filter: is_test = fold_by_student == fold. It also works as sklearn's
    PredefinedSplit(test_fold=fold_by_student) if a function wants a cv= argument.
    """
    folds_df = load_folds() if folds_df is None else folds_df
    fold_by_school = folds_df.set_index(SCHOOL_COL)["fold"]
    fold_by_student = table_df[SCHOOL_COL].map(fold_by_school)
    if fold_by_student.isna().any():
        raise ValueError("some schools are not in the fold file; was it made from a different table?")
    return fold_by_student.astype(int).rename("fold")


def make_inner_cv(n_splits: int = 3, seed: int = FOLD_SEED) -> StratifiedGroupKFold:
    """Folds *inside* one training set, for tuning hyperparameters (e.g. GridSearchCV(cv=make_inner_cv())).

    Pass groups=train_df["CNTSCHID"] to the search's .fit(), so schools stay whole while tuning too.
    """
    return StratifiedGroupKFold(n_splits=n_splits, shuffle=True, random_state=seed)


# ---------------------------------------------------------------------------------------------------------
# Choosing the model inputs
# ---------------------------------------------------------------------------------------------------------
def get_feature_cols(groups: list[str] | None = None, *, with_missing_flags: bool = True,
                     system_as_feature: bool | None = None, family_as_escs_only: bool | None = None) -> list[str]:
    """The model input columns for the chosen factor groups (default: all 5).

    A group's missing flags come and go with the group, so an ablation that drops a group drops both.
    system_as_feature and family_as_escs_only default to the team settings at the top of this file.
    """
    groups = GROUPS if groups is None else list(groups)
    unknown_groups = [group for group in groups if group not in GROUPS]
    if unknown_groups:
        raise ValueError(f"unknown groups {unknown_groups}; choose from {GROUPS}")
    system_as_feature = USE_SYSTEM_AS_FEATURE if system_as_feature is None else system_as_feature
    family_as_escs_only = FAMILY_AS_ESCS_ONLY if family_as_escs_only is None else family_as_escs_only

    feature_cols, flag_cols = [], []
    for group in groups:
        group_cols = ["ESCS"] if (group == "family" and family_as_escs_only) else FEATURES_BY_GROUP[group]
        feature_cols += group_cols
        if with_missing_flags:
            flag_cols += [flag_col for flag_col in MISSING_FLAGS_BY_GROUP[group]
                          if flag_col.removesuffix("_missing") in group_cols]
    if system_as_feature:
        feature_cols.append(SYSTEM_COL)
    return feature_cols + flag_cols


def check_no_leakage(cols: list[str]) -> None:
    """Stop with an error if any column in cols must never be a model input."""
    leaky_cols = [col for col in cols if LEAKY_COL_PATTERN.match(col)]
    if leaky_cols:
        raise ValueError(f"these columns must never be model inputs (leakage): {leaky_cols}")


# ---------------------------------------------------------------------------------------------------------
# T08: the preprocessing pipeline. Every step learns its numbers in .fit() (training rows only)
# and reuses them in .transform() (test rows).
# ---------------------------------------------------------------------------------------------------------
class PercentileClipper(OneToOneFeatureMixin, TransformerMixin, BaseEstimator):
    """Cap each column at percentiles learned from the training rows ("winsorising").

    Blanks stay blank, so the imputer after this step still sees them.
    """

    def __init__(self, lower_pct: float = 1.0, upper_pct: float = 99.0):
        self.lower_pct = lower_pct
        self.upper_pct = upper_pct

    def fit(self, inputs: pd.DataFrame | np.ndarray, y: None = None) -> "PercentileClipper":
        values = validate_data(self, inputs, ensure_all_finite="allow-nan", dtype=float)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", RuntimeWarning)          # an all-blank column has no percentiles
            lower_bounds = np.nanpercentile(values, self.lower_pct, axis=0)
            upper_bounds = np.nanpercentile(values, self.upper_pct, axis=0)
        self.lower_bounds_ = np.where(np.isnan(lower_bounds), -np.inf, lower_bounds)   # all-blank: no cap
        self.upper_bounds_ = np.where(np.isnan(upper_bounds), np.inf, upper_bounds)
        return self

    def transform(self, inputs: pd.DataFrame | np.ndarray) -> np.ndarray:
        check_is_fitted(self)
        values = validate_data(self, inputs, ensure_all_finite="allow-nan", dtype=float, reset=False)
        return np.clip(values, self.lower_bounds_, self.upper_bounds_)


def make_preprocessor(feature_cols: list[str], *, clip: bool | None = None, scale: bool = True) -> ColumnTransformer:
    """The preprocessing steps, each applied to the columns it suits:

    - numeric features: clip at training percentiles -> fill blanks with the training median -> scale to mean 0, sd 1
    - 0/1 features (SCHL_PRIVATE): fill blanks with the most common training value
    - missing flags: passed through unchanged (they are already 0/1 and have no blanks)
    - the system (CNT), if chosen: one 0/1 column per system

    clip defaults to the team setting CLIP_PERCENTILES. Scaling is needed for logistic regression, k-NN and
    neural networks; trees ignore it, so scale=False is fine for them.
    """
    check_no_leakage(feature_cols)
    clip = CLIP_PERCENTILES is not None if clip is None else clip
    flag_cols = [col for col in feature_cols if col.endswith("_missing")]
    binary_cols = [col for col in feature_cols if col in BINARY_FEATURE_COLS]
    system_cols = [col for col in feature_cols if col == SYSTEM_COL]
    numeric_cols = [col for col in feature_cols if col not in flag_cols + binary_cols + system_cols]

    numeric_steps = []
    if clip:
        numeric_steps.append(("clip", PercentileClipper(*(CLIP_PERCENTILES or (1.0, 99.0)))))
    numeric_steps.append(("fill_blanks", SimpleImputer(strategy="median", keep_empty_features=True)))
    if scale:
        numeric_steps.append(("scale", StandardScaler()))

    parts = []
    if numeric_cols:
        parts.append(("numeric", Pipeline(numeric_steps), numeric_cols))
    if binary_cols:
        parts.append(("binary", SimpleImputer(strategy="most_frequent", keep_empty_features=True), binary_cols))
    if flag_cols:
        parts.append(("missing_flags", "passthrough", flag_cols))
    if system_cols:
        parts.append(("system", OneHotEncoder(handle_unknown="ignore", sparse_output=False), system_cols))
    return ColumnTransformer(parts, remainder="drop", verbose_feature_names_out=False).set_output(transform="pandas")


def make_model_pipeline(model: BaseEstimator, feature_cols: list[str], **preprocessor_options) -> Pipeline:
    """Preprocessing + model in one object. .fit() learns everything from the rows it is given (training only).

    Pass weights as model__sample_weight=... in .fit(). preprocessor_options go to make_preprocessor().
    """
    return Pipeline([("prep", make_preprocessor(feature_cols, **preprocessor_options)), ("model", model)])


# ---------------------------------------------------------------------------------------------------------
# Targets and weights
# ---------------------------------------------------------------------------------------------------------
def get_target_col(task: str, pv: int) -> str:
    """The target column for one plausible value (pv = 1 to 10).

    task "regression" -> "PV{pv}MATH" (the maths score); task "classification" -> "BELOW_L2_PV{pv}" (1 = below Level 2).
    """
    if not 1 <= pv <= 10:
        raise ValueError("pv must be 1 to 10")
    target_col_by_task = {"regression": PV_COLS[pv - 1], "classification": BELOW_L2_COLS[pv - 1]}
    if task not in target_col_by_task:
        raise ValueError('task must be "regression" or "classification"')
    return target_col_by_task[task]


def get_weight_col(table_df: pd.DataFrame) -> str:
    """POOLED_WEIGHT_COL when table_df has several systems, W_FSTUWT when it has one.

    Within one system SENWT is just W_FSTUWT times a constant (up to rounding), so for a single system they give the same results.
    """
    return POOLED_WEIGHT_COL if table_df[SYSTEM_COL].nunique() > 1 else "W_FSTUWT"


def get_sample_weights(table_df: pd.DataFrame, weight_col: str | None = None) -> np.ndarray:
    """Survey weights for fitting or scoring a model, rescaled to average 1.

    Rescaling doesn't change which students count more. It keeps the total weight equal to the number of
    students, so regularisation settings (C in logistic regression, alpha in ridge/MLP) mean the same as without weights.
    """
    weight_col = get_weight_col(table_df) if weight_col is None else weight_col
    weights = table_df[weight_col].to_numpy(dtype=float)
    return weights / weights.mean()
